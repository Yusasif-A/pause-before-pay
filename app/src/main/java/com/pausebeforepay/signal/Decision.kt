package com.pausebeforepay.signal

import com.presagetech.smartspectra.ValidationCode
import com.presagetech.smartspectra.proto.MetricsProto.ExpressionType
import kotlin.math.roundToInt

enum class Verdict {
    /** Nothing clearly above this person's own resting state. Confirm unlocks. */
    CALM,

    /** Clearly above. Offer a pause -- but never block. */
    ELEVATED,

    /** Not enough trustworthy signal to say anything. Treated as not elevated. */
    LOW_CONFIDENCE,
}

enum class Basis {
    /** Compared against this person's stored calibration scan. */
    PERSONAL_BASELINE,

    /** No calibration yet, so absolute thresholds were used. */
    ABSOLUTE_FALLBACK,

    /** The rates were unusable but the face was read clearly. */
    FACE_ONLY,

    /** Too few accepted samples of anything to say something. */
    INSUFFICIENT_SIGNAL,
}

data class Decision(
    val verdict: Verdict,
    val basis: Basis,
    val pulseBpm: Double?,
    val breathingBrpm: Double?,
    val pulseDeltaBpm: Double?,
    val breathingDeltaBrpm: Double?,
    /**
     * The plain-language read of the moment: "You seem to be rushing".
     * Code-generated, never an LLM.
     */
    val headline: String,
    /** Which rules fired, in plain words. Always generated by code, never an LLM. */
    val explanation: String,
    /** Guidance to show when the signal was poor. */
    val guidance: String?,
    /** Null when the face was not read at all, which is not the same as settled. */
    val faceTense: Boolean? = null,
    val dominantExpression: ExpressionType? = null,
    val pulseFired: Boolean = false,
    val breathingFired: Boolean = false,
    val faceFired: Boolean = false,
) {
    /** True when the Confirm button must stay locked until the user acts. */
    val blocksConfirm: Boolean get() = verdict == Verdict.ELEVATED

    /** A short chip for the face, or null when the face was not read. */
    val faceLabel: String?
        get() = when (faceTense) {
            true -> "tense"
            false -> "settled"
            null -> null
        }
}

/**
 * The whole gate, in one pure function.
 *
 * Three independent triggers, any one of which offers the pause:
 *  - pulse clearly above this person's resting pulse,
 *  - breathing clearly faster than their resting breathing,
 *  - a face that read as tense for a sustained part of the scan.
 *
 * Deliberately deterministic: same numbers in, same verdict out. No network, no
 * model weights, no randomness, no language model. Unit-tested in
 * app/src/test/java/com/pausebeforepay/signal/DecisionEngineTest.kt.
 *
 * It describes what was measured and asks a question. It never concludes
 * anything about why, and it never blocks a payment.
 */
object DecisionEngine {

    fun decide(summary: ScanSummary, baseline: Baseline?): Decision {
        val pulse = summary.pulseBpm
        val breathing = summary.breathingBrpm
        val faceTense = summary.faceTense
        val faceFired = faceTense == true

        val ratesUsable = pulse != null &&
            summary.pulseSamples >= Thresholds.SCAN_MIN_PULSE_SAMPLES

        // The rates were unusable. The face may still have been read clearly,
        // and a clearly tense face is a reading, not a failed one.
        if (!ratesUsable) {
            if (faceFired) {
                return Decision(
                    verdict = Verdict.ELEVATED,
                    basis = Basis.FACE_ONLY,
                    pulseBpm = pulse,
                    breathingBrpm = breathing,
                    pulseDeltaBpm = null,
                    breathingDeltaBrpm = null,
                    headline = "You seem tense",
                    explanation = "Your face looked tense during the check. Your pulse " +
                        "could not be read clearly enough to compare, so this is based " +
                        "on the face alone.",
                    guidance = null,
                    faceTense = true,
                    dominantExpression = summary.dominantExpression,
                    faceFired = true,
                )
            }
            return Decision(
                verdict = Verdict.LOW_CONFIDENCE,
                basis = Basis.INSUFFICIENT_SIGNAL,
                pulseBpm = pulse,
                breathingBrpm = breathing,
                pulseDeltaBpm = null,
                breathingDeltaBrpm = null,
                headline = "The check could not read you clearly",
                explanation = "Nothing is being held up. Take a moment to check the " +
                    "details below before you send.",
                guidance = guidanceFor(summary.dominantIssue),
                faceTense = faceTense,
                dominantExpression = summary.dominantExpression,
            )
        }

        requireNotNull(pulse)

        val usingBaseline = baseline != null
        val pulseDelta = if (baseline != null) pulse - baseline.restingPulseBpm else null
        val restingBreathing = baseline?.restingBreathingBrpm
        val breathingDelta =
            if (breathing != null && restingBreathing != null) {
                breathing - restingBreathing
            } else {
                null
            }

        val pulseFired = if (baseline != null) {
            (pulseDelta ?: 0.0) >= Thresholds.ELEVATED_PULSE_DELTA_BPM
        } else {
            pulse >= Thresholds.ABSOLUTE_PULSE_BPM
        }

        val breathingFired = if (baseline != null) {
            breathingDelta != null && breathingDelta >= Thresholds.ELEVATED_BREATHING_DELTA_BRPM
        } else {
            breathing != null && breathing >= Thresholds.ABSOLUTE_BREATHING_BRPM
        }

        val elevated = pulseFired || breathingFired || faceFired

        return Decision(
            verdict = if (elevated) Verdict.ELEVATED else Verdict.CALM,
            basis = if (usingBaseline) Basis.PERSONAL_BASELINE else Basis.ABSOLUTE_FALLBACK,
            pulseBpm = pulse,
            breathingBrpm = breathing,
            pulseDeltaBpm = pulseDelta,
            breathingDeltaBrpm = breathingDelta,
            headline = headline(elevated, pulseFired || breathingFired, faceFired),
            explanation = explain(
                elevated = elevated,
                usingBaseline = usingBaseline,
                pulseFired = pulseFired,
                breathingFired = breathingFired,
                faceFired = faceFired,
                faceTense = faceTense,
                pulse = pulse,
                pulseDelta = pulseDelta,
                breathingDelta = breathingDelta,
                breathing = breathing,
            ),
            guidance = null,
            faceTense = faceTense,
            dominantExpression = summary.dominantExpression,
            pulseFired = pulseFired,
            breathingFired = breathingFired,
            faceFired = faceFired,
        )
    }

    /**
     * The plain-language read. Hedged on purpose -- "seem", not "are". The app
     * measured a body, not a state of mind, and the copy must not pretend
     * otherwise.
     */
    private fun headline(elevated: Boolean, ratesFired: Boolean, faceFired: Boolean): String =
        when {
            !elevated -> "You look settled"
            ratesFired && faceFired -> "You seem rushed and tense"
            faceFired -> "You seem tense"
            else -> "You seem to be rushing"
        }

    private fun explain(
        elevated: Boolean,
        usingBaseline: Boolean,
        pulseFired: Boolean,
        breathingFired: Boolean,
        faceFired: Boolean,
        faceTense: Boolean?,
        pulse: Double,
        pulseDelta: Double?,
        breathing: Double?,
        breathingDelta: Double?,
    ): String {
        val evidence = buildList {
            if (pulseFired) {
                add(
                    if (usingBaseline && pulseDelta != null) {
                        "your pulse is about ${pulseDelta.roundToInt()} bpm above your " +
                            "usual resting rate"
                    } else {
                        "your pulse read about ${pulse.roundToInt()} bpm"
                    },
                )
            }
            if (breathingFired) {
                add(
                    if (usingBaseline && breathingDelta != null) {
                        "you are breathing about ${breathingDelta.roundToInt()} breaths " +
                            "per minute faster than usual"
                    } else {
                        "you are breathing about ${breathing?.roundToInt()} breaths per minute"
                    },
                )
            }
            if (faceFired) add("your face looked tense for most of the check")
        }

        val fallbackNote = if (usingBaseline) {
            ""
        } else {
            " (No baseline saved yet, so this uses general thresholds instead of your " +
                "own resting rates.)"
        }

        if (!elevated) {
            val settled = buildString {
                append(
                    if (usingBaseline && pulseDelta != null) {
                        val delta = pulseDelta.roundToInt()
                        if (delta <= 0) {
                            "Your pulse is at or below your usual resting rate"
                        } else {
                            "Your pulse is about $delta bpm above your usual resting rate, " +
                                "which is within your normal range"
                        }
                    } else {
                        "Your pulse read about ${pulse.roundToInt()} bpm"
                    },
                )
                if (faceTense == false) append(", and your face looked settled")
                append(".")
            }
            return settled + fallbackNote
        }

        return evidence.joinToString(", and ").replaceFirstChar { it.uppercase() } +
            "." + fallbackNote
    }

    /** Maps the SDK's validation code onto something a person can act on. */
    fun guidanceFor(code: ValidationCode?): String = when (code) {
        ValidationCode.TOO_DARK ->
            "It was too dark. Move somewhere brighter and try again."
        ValidationCode.TOO_BRIGHT ->
            "There was too much light. Move out of direct light and try again."
        ValidationCode.NO_FACE_FOUND ->
            "Your face was not in the picture. Hold the phone in front of your face."
        ValidationCode.MULTIPLE_FACES_FOUND ->
            "More than one face was in the picture. Make sure only you are in frame."
        ValidationCode.FACE_NOT_CENTERED ->
            "Centre your face in the picture and try again."
        ValidationCode.FACE_SIZE_OUT_OF_RANGE ->
            "Hold the phone about an arm length away and try again."
        ValidationCode.FACE_TOO_CLOSE ->
            "Hold the phone a little further away and try again."
        ValidationCode.FACE_TOO_FAR ->
            "Hold the phone a little closer and try again."
        ValidationCode.FACE_TOO_HIGH ->
            "Lower the phone slightly so your face is centred."
        ValidationCode.FACE_TOO_LOW ->
            "Raise the phone slightly so your face is centred."
        ValidationCode.FACE_NOT_FORWARD ->
            "Look straight at the phone and try again."
        ValidationCode.CHEST_NOT_VISIBLE ->
            "Hold the phone so your face and upper chest are both in the picture."
        ValidationCode.EXCESSIVE_MOTION ->
            "Hold still and try again."
        ValidationCode.FRAME_RATE_TOO_LOW ->
            "The camera was delivering frames too slowly. Move into brighter light, " +
                "and stop screen recording or other apps using the camera."
        ValidationCode.CAMERA_TUNING ->
            "The camera was still adjusting. Try again."
        ValidationCode.OK, null ->
            "Sit still, keep your face and upper chest in the picture, and try again."
    }
}
